/** The rendered `alt`/`title` for one gallery photo: its own description of what the photo shows. */
export function seoAlt(img: Pick<GalleryImage, "alt" | "category">): string {
  return img.alt
}

/** Absolute, canonical photo URL — schema.org `ImageObject.contentUrl` wants a full URL, not a root-relative path. */
export function absoluteImageUrl(src: string): string {
  return `${SITE_URL}${src}`
}

/** The /gallery page's ImageGallery: every photo with the same description its alt text carries. */
export function buildGalleryJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "ImageGallery",
    "@id": `${SITE_URL}/gallery#imagegallery`,
    name: "JK Interior project gallery",
    description:
      "Photographs of false ceilings, partition walls, wall panelling, TV units and artificial grass installed by JK Interior around Forbesganj and Araria district, Bihar.",
    url: `${SITE_URL}/gallery`,
    author: businessRef(),
    image: galleryImages.map((img) => ({
      "@type": "ImageObject",
      contentUrl: absoluteImageUrl(img.src),
      caption: img.alt,
      width: img.width,
      height: img.height,
    })),
  }
}
